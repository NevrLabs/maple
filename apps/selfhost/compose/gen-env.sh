#!/usr/bin/env bash
# Build the CT's compose .env from the k3s Secrets (same keys/passwords => migrated PG data stays readable,
# ingest keys keep validating). Writes ~/deploy/maple/selfhost/compose/.env (mode 600, gitignored). Never prints values.
set -euo pipefail
export KUBECONFIG=~/.kube/fxcluster-admin.yaml
out=~/deploy/maple/selfhost/compose/.env
g() { kubectl -n maple get secret "$1" -o jsonpath="{.data.$2}" | base64 -d; }
umask 077
{
  echo "# generated by gen-env.sh $(date -u +%FT%TZ) — SECRET, do not commit"
  echo "MAPLE_PUBLIC_ORIGIN=https://monitoring.home"
  echo "MAPLE_INGEST_URL=http://192.168.100.30:3474"
  echo "MAPLE_SELFHOST_TAG=${MAPLE_SELFHOST_TAG:-f6412d8}"
  echo "MAPLE_WEB_TAG=${MAPLE_WEB_TAG:-1a5256f}"
  echo "MAPLE_COLLECTOR_TAG=01a41da"
  echo "MAPLE_INGEST_TAG=01a41da"
  echo "POSTGRES_PASSWORD=$(g maple-postgres POSTGRES_PASSWORD)"
  echo "CH_ADMIN_PASSWORD=$(g maple-clickhouse CH_ADMIN_PASSWORD)"
  echo "CH_RUNTIME_PASSWORD=$(g maple-clickhouse CH_RUNTIME_PASSWORD)"
  echo "CH_INGEST_PASSWORD=$(g maple-clickhouse CH_INGEST_PASSWORD)"
  for k in MAPLE_ROOT_PASSWORD INTERNAL_SERVICE_TOKEN SD_INTERNAL_TOKEN MAPLE_INGEST_KEY_ENCRYPTION_KEY MAPLE_INGEST_KEY_LOOKUP_HMAC_KEY MAPLE_SHARE_TOKEN_HMAC_KEY; do
    echo "$k=$(g maple-app $k)"
  done
} > "$out"
# sanity: every key non-empty, nothing printed
awk -F= '/^[A-Z]/ && $2=="" {print "EMPTY: "$1; bad=1} END {exit bad}' "$out"
grep -c '^[A-Z]' "$out" | sed 's/^/keys: /'
