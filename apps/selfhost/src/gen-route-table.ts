// Generates apps/selfhost/src/route-table.generated.ts from the live HttpApi definitions:
// every endpoint's method, path pattern and identifier (group.endpoint). Run: bun src/gen-route-table.ts
import { HttpApi } from "effect/http-api"
import { MapleApi } from "@maple/domain/http"
import { MapleAiApi, MapleInternalApi } from "@maple/domain/http"
import { MapleApiV2 } from "@maple/domain/http/v2"

const rows: Array<[string, string, string]> = []
for (const api of [MapleApi, MapleInternalApi, MapleApiV2, MapleAiApi]) {
	HttpApi.reflect(api as never, {
		onGroup: () => {},
		onEndpoint: (e: { group: { identifier: string }; endpoint: { method: string; path: string; name?: string; identifier?: string } }) => {
			rows.push([e.endpoint.method, e.endpoint.path, `${e.group.identifier}.${e.endpoint.identifier ?? e.endpoint.name}`])
		},
	})
}
rows.sort((a, b) => (a[1] + a[0]).localeCompare(b[1] + b[0]))
const body = rows.map(([m, p, id]) => `\t[${JSON.stringify(m)}, ${JSON.stringify(p)}, ${JSON.stringify(id)}],`).join("\n")
await Bun.write(
	new URL("./route-table.generated.ts", import.meta.url),
	`// GENERATED by gen-route-table.ts from the HttpApi definitions (${rows.length} endpoints). Do not edit.\n` +
		`// Regenerate after an upstream rebase; route-policy.test.ts fails if a mutating endpoint is unclassified.\n` +
		`export const ROUTES: ReadonlyArray<readonly [method: string, path: string, id: string]> = [\n${body}\n]\n`,
)
console.log(`wrote ${rows.length} routes`)
